def launchd_pid(target: str, *, deadline=None) -> int | None:
    """PID that `launchctl print <target>` reports, or None when not running/unknown."""
    r = lifecycle_io.run_bounded(["launchctl", "print", target], timeout=10,
             **({} if deadline is None else {"deadline": deadline}))
    match = re.search(r"^\s*pid = (\d+)$", getattr(r, "stdout", "") or "", re.M)
    return int(match.group(1)) if r.returncode == 0 and match and int(match.group(1)) > 0 else None


def gateway_sources_mtime(checkout: str, dirs=mcs_runtime.GATEWAY_SOURCE_DIRS, *, deadline=None) -> float | None:
    """Newest gateway-loaded source timestamp; absent sources remain unknown."""
    newest = 0.0
    # __pycache__/*.pyc are regenerated BY the gateway at plugin load —
    # counting them makes the warning permanent. Only files the gateway
    # loads (Python sources and the plugin manifest) represent code the
    # running process hasn't picked up; a docs-only edit (README) never
    # needs a restart.
    for source in dirs:
        for base, subdirs, files in os.walk(os.path.join(checkout, source)):
            if deadline is not None and time.monotonic() >= deadline:
                raise TimeoutError("release_prequiesce_timeout")
            subdirs[:] = [d for d in subdirs if d != "__pycache__"]
            for name in files:
                if not name.endswith((".py", ".yaml", ".yml")):
                    continue
                with suppress(OSError):
                    newest = max(newest, os.path.getmtime(
                        os.path.join(base, name)))
    return newest or None


