def plugin_newer_than_gateway(status_out: str, *, checkout: str, deadline=None) -> bool:
    """Detect gateway-loaded plugin or adapter sources newer than the running process.

    Unparseable states fail
    open to False (no warning) rather than a false alarm."""
    m = re.search(r"PID\s+(\d+)", status_out or "")
    started = process_started_at(int(m.group(1)), **({} if deadline is None else {"deadline": deadline})) if m else None
    if started is None:
        return False
    newest = gateway_sources_mtime(checkout, **({} if deadline is None else {"deadline": deadline}))
    return newest is not None and newest > started


def process_started_at(pid: int, *, deadline=None) -> float | None:
    """Local-time start of `pid` from `ps -o lstart=`, or None when unknown.

    LC_ALL=C keeps the stamp in the English format strptime parses
    (a ja_JP locale prints the weekday in kanji)."""
    r = lifecycle_io.run_bounded(["ps", "-o", "lstart=", "-p", str(pid)], timeout=10,
             env={**os.environ, "LC_ALL": "C"}, **({} if deadline is None else {"deadline": deadline}))
    if r.returncode != 0:
        return None
    stamp = re.sub(r"\s+", " ", (getattr(r, "stdout", "") or "").strip())
    try:
        return time.mktime(time.strptime(stamp, "%a %b %d %H:%M:%S %Y"))
    except (ValueError, OverflowError):
        return None


