def test_outbox_and_job_fixed_values_are_counted_without_copying_unknown_text(inventory_world):
    source, _ = inventory_world
    kinds = ("reply", "thread", "history", "history_head", "reconcile", "discovery",
             "semantic", "extract_qc", "semantic_sched", "extract_claim", "extract_stale_gc",
             "intervention_source_reconcile", "patient_context_summary_quality_claim",
             "semantic_intake_unstored_v1", "semantic_intake_unstored_epoch_v1",
             "semantic_intake_unstored_root_v1", "semantic_intake_archive_v1")
    with closing(sqlite3.connect(source)) as db:
        with db:
            for state in ("pending", "accepted", "failed", "suppressed", "private-outbox", None):
                db.execute("INSERT INTO notify_outbox(kind,payload,state,created_at) VALUES('synthetic','{}',?,?)",
                           (state, NOW))
            for kind in (*kinds, "private-kind", None):
                db.execute("INSERT INTO fetch_jobs(kind,project_id,state) VALUES(?,1,'pending')", (kind,))
            for message_id, state in enumerate(("done", "failed", "private-job", None), 1):
                db.execute("INSERT INTO fetch_jobs(kind,project_id,message_id,state) VALUES('reply',1,?,?)",
                           (message_id, state))
    result = backup_evidence.inventory_snapshot(source)
    assert result["states"]["notify_outbox"] == {
        "pending": 1, "accepted": 1, "failed": 1, "suppressed": 1, "other": 2}
    assert set(result["jobs"]) == {*kinds, "other"}
    assert result["jobs"]["reply"] == {"pending": 1, "done": 1, "failed": 1, "other": 2}
    assert all(result["jobs"][kind] == {"pending": 1, "done": 0, "failed": 0, "other": 0}
               for kind in kinds if kind != "reply")
    assert result["jobs"]["other"] == {"pending": 2, "done": 0, "failed": 0, "other": 0}
    assert result["states"]["fetch_jobs"] == {"pending": 19, "done": 1, "failed": 1, "other": 2}
    assert "private-" not in json.dumps(result)
