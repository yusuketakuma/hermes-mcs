def _bundle(source, policy, monkeypatch, legacy):
    with monkeypatch.context() as patch:
        if legacy:
            collector = backup_evidence.inventory_snapshot
            def legacy_writer(path, **kwargs):
                return collector(path, **kwargs) if kwargs else _legacy_inventory()
            patch.setattr(backup_evidence, "inventory_snapshot", legacy_writer)
        return backup.offsite(str(source), policy, lambda: KEY)


def _change_inventory(receipt, mutate):
    path = Path(receipt["bundle"])
    raw = path.read_bytes()
    length = int.from_bytes(raw[8:12], "big")
    manifest = json.loads(raw[12:12 + length])
    mutate(manifest["inventory"])
    header = backup._canonical(manifest)
    signed = raw[:8] + len(header).to_bytes(4, "big") + header + raw[12 + length:-32]
    tag = hmac.new(backup._mac_key(KEY, bytes.fromhex(manifest["mac_salt"])), signed, hashlib.sha256)
    path.write_bytes(signed + tag.digest())
    return backup.file_sha256(path)


def test_new_inventory_counts_persisted_states_and_keeps_private_values_hidden(inventory_world):
    source, _ = inventory_world
    result = backup_evidence.inventory_snapshot(source)
    assert result["v"] == 2
    assert result["states"]["patients"] == {
        "pending": 1, "complete": 1, "incomplete": 1, "forbidden": 1, "other": 4}
    assert "private-unknown" not in json.dumps(result)
    assert backup_evidence.inventory_snapshot(source, max_steps=10_000_000) == result
    assert backup_evidence.inventory_matches(source, result, max_steps=10_000_000)
    assert backup_evidence.inventory_snapshot(source, version=1) == _legacy_inventory()
    assert backup_evidence.inventory_matches(source, _legacy_inventory())
    assert backup_evidence.inventory_matches(source, _legacy_inventory(), max_steps=10_000_000)


@pytest.mark.parametrize("version", [None, True, False, 0, 1, 2.0, 3, "2", [], {}])
def test_explicit_invalid_inventory_version_is_rejected_before_read(inventory_world, monkeypatch, version):
    source, _ = inventory_world
    expected = _legacy_inventory()
    expected["v"] = version
    monkeypatch.setattr(backup_evidence, "inventory_snapshot", lambda *a, **k: pytest.fail("invalid version read DB"))
    assert not backup_evidence.inventory_matches(source, expected)


@pytest.mark.parametrize("legacy", [False, True])
def test_old_and_new_bundle_verify_and_held_consent_preserve_data(inventory_world, monkeypatch, legacy):
    source, policy = inventory_world
    receipt = _bundle(source, policy, monkeypatch, legacy)
    before = backup.file_sha256(source)
    target = Path(policy.scratch_dir) / "held"
    report = backup.restore(receipt["bundle"], receipt["sha256"], policy,
                            lambda: KEY, destination=str(target))
    assert report["inventory"].get("v") == (None if legacy else 2)
    plan = restore.plan(str(target), source_sha256=receipt["sha256"])
    approval = restore.approve(
        str(target), source_sha256=receipt["sha256"], plan_sha256=plan["plan_sha256"],
        confirm_human=True, actor="synthetic-owner", reason="synthetic recovery reviewed",
        custody_ref="synthetic-custody", delivery_policy="hold_all")
    assert approval["receipt_sha256"]
    assert backup.file_sha256(source) == before == backup.file_sha256(target / "ledger.db")
    assert (target / restore.MARKER).exists()


@pytest.mark.parametrize("legacy", [False, True])
def test_version_cannot_be_added_or_removed_to_reinterpret_authenticated_inventory(inventory_world, monkeypatch, legacy):
    source, policy = inventory_world
    receipt = _bundle(source, policy, monkeypatch, legacy)
    digest = _change_inventory(receipt, lambda value: value.update(v=2) if legacy else value.pop("v"))
    with pytest.raises(backup_evidence.BackupError, match="backup_inventory_mismatch"):
        backup.verify(receipt["bundle"], digest, policy, lambda: KEY)


