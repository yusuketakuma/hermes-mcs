@pytest.mark.parametrize("transport", ["json", "ndjson", "directory"])
def test_manual_receipt_import_reconciles_handoff_without_resend(
        inputs, capsys, tmp_path, transport):
    _, result = _cli(capsys, ["handoff", *_flags(inputs)])
    eid = result["envelope_id"]
    receipt = _accepted(inputs, eid)
    path = tmp_path / "receipts.json"
    path.write_text(json.dumps(receipt))
    if transport == "ndjson":
        path.write_text(json.dumps(receipt) + "\n" + json.dumps(receipt) + "\n")
    elif transport == "directory":
        directory = tmp_path / "receipts"
        directory.mkdir()
        path.rename(directory / "one.json")
        path = directory
    code, imported = _cli(capsys, [
        "reconcile", "--state", inputs["state"], "--sink", inputs["sink"],
        "--receipts", str(path)])
    assert code == 0
    assert {row["status"] for row in imported["results"]} == {"acked"}
    assert not (Path(inputs["sink"]) / "envelopes" / f"{eid}.json").exists()
    assert (Path(inputs["sink"]) / "acks" / f"{eid}.json").exists()
    _, again = _cli(capsys, ["handoff", *_flags(inputs)])
    assert again["status"] == "already_acked"


