def test_health_counts_and_authorization_are_readonly_and_redacted(
        inputs, capsys, tmp_path, monkeypatch):
    _, result = _cli(capsys, ["handoff", *_flags(inputs)])
    journal = Path(inputs["state"]) / "journal"
    for number, status in enumerate(
            ("held", "delete_held", "acked", "withdrawn", "refused", "rejected"), 1):
        eid = f"{number:024x}"
        (journal / f"{eid}.json").write_text(json.dumps({
            "envelope_id": eid, "status": status,
            "attempts": [{"ts": NOW - 30, "status": status}],
            "actor": "SYNTH_ACTOR_SECRET", "body": "SYNTH_BODY_SECRET",
            "reason": "SYNTH_REASON_SECRET", "sink_root": inputs["sink"]}))
    (journal / ("f" * 24 + ".json")).write_text("{corrupt")
    payload = Path(inputs["sink"]) / "envelopes" / f'{result["envelope_id"]}.json'
    payload.unlink()
    before = _tree(tmp_path)

    def forbidden(*args, **kwargs):
        pytest.fail("health invoked a writer or sink action")

    monkeypatch.setattr(ext, "GovernedExporter", forbidden)
    monkeypatch.setattr(ext, "HandoffSink", forbidden)
    monkeypatch.setattr(ext, "_write_json", forbidden)
    code, report = _cli(capsys, [
        "health", "--state", inputs["state"], "--auth", inputs["auth"],
        "--sink", inputs["sink"]])
    assert code == 2 and report["status"] == "unknown"
    assert report["counts"] == {
        "held": 2, "delete_held": 1, "acked": 1, "withdrawn": 1,
        "refused": 1, "rejected": 1, "corrupt": 1}
    assert report["oldest_held_age_s"] == 30
    assert report["authorization"] == {"state": "valid", "seconds_left": 3600}
    assert "payload_missing" in report["reasons"]
    assert report["complete"] is False
    output = json.dumps(report)
    assert "SECRET" not in output and str(tmp_path) not in output
    assert result["envelope_id"] not in output
    assert _tree(tmp_path) == before


@pytest.mark.parametrize("case", ["missing", "oversized", "symlink", "fifo",
                                "entry_limit", "invalid_auth", "expired_auth",
                                "revoked_auth", "invalid_budget"])
def test_health_negative_inputs_are_bounded_redacted_and_unchanged(
        inputs, capsys, tmp_path, case):
    _, result = _cli(capsys, ["handoff", *_flags(inputs)])
    journal = Path(inputs["state"]) / "journal" / f'{result["envelope_id"]}.json'
    extra = []
    if case == "missing":
        inputs["state"] = str(tmp_path / "absent")
    elif case == "oversized":
        journal.write_bytes(b" " * (ext.RECEIPT_MAX_BYTES + 1))
    elif case == "symlink":
        journal.unlink()
        journal.symlink_to(inputs["auth"])
    elif case == "fifo":
        journal.unlink()
        os.mkfifo(journal)
    elif case == "entry_limit":
        (journal.parent / ("f" * 24 + ".json")).write_text("{}")
        extra = ["--max-entries", "1"]
    elif case == "invalid_auth":
        Path(inputs["auth"]).write_text(json.dumps({"SYNTH_AUTH_SECRET": "SYNTH_SECRET"}))
    elif case in ("expired_auth", "revoked_auth"):
        path = Path(inputs["auth"])
        auth = json.loads(path.read_text())
        auth.update({"expires_at": NOW - 1} if case == "expired_auth" else {"revoked": True})
        path.write_text(json.dumps(auth))
    else:
        extra = ["--max-entries", "0"]
    before = _tree(tmp_path)
    code, report = _cli(capsys, [
        "health", "--state", inputs["state"], "--auth", inputs["auth"], *extra])
    assert code in (1, 2)
    assert report["status"] in ("unknown", "refused")
    assert "SYNTH" not in json.dumps(report) and str(tmp_path) not in json.dumps(report)
    assert _tree(tmp_path) == before
    if case == "entry_limit":
        assert report["complete"] is False and "journal_entry_limit" in report["reasons"]


@pytest.mark.parametrize("action", ["legacy", "handoff", "health"])
def test_direct_script_entry_preserves_old_invocation_and_local_commands(
        inputs, tmp_path, action):
    repo = Path(__file__).resolve().parents[2]
    # Load the existing sandbox guards before running the actual script.
    code = ("import runpy,sys,time;runpy.run_path(sys.argv.pop(1));"
            "time.time=lambda:1800000000.0;"
            "runpy.run_path(sys.argv.pop(1),run_name='__main__')")
    if action == "health":
        arguments = ["health", "--state", inputs["state"], "--auth", inputs["auth"]]
    else:
        arguments = ([] if action == "legacy" else ["handoff"]) + _flags(inputs)
    before = _tree(tmp_path) if action == "health" else None
    result = subprocess.run(
        [sys.executable, "-c", code, str(repo / "tests/conftest.py"),
         str(repo / "mcs/ops/ext_contract.py"), *arguments],
        capture_output=True, text=True, timeout=10, check=False)
    report = json.loads(result.stdout)
    assert result.returncode == (2 if action == "health" else 0), result.stderr
    assert report["status"] == {"legacy": "acked", "handoff": "held", "health": "unknown"}[action]
    if before is not None:
        assert _tree(tmp_path) == before


def test_real_synthetic_database_export_handoff_round_trip(tmp_path, capsys):
    import brain_export
    import ledger
    from semantic_testkit import _ledger, _message, _patient

    db = _ledger(tmp_path)
