def _flags(inputs):
    return [value for key, value in inputs.items() for value in ("--" + key, value)]


def _cli(capsys, arguments):
    code = ext.main(arguments)
    return code, json.loads(capsys.readouterr().out)


def _tree(root):
    result = {}
    for path in [root, *sorted(root.rglob("*"))]:
        st = path.lstat()
        content = (os.readlink(path) if path.is_symlink() else
                   hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None)
        result[str(path.relative_to(root))] = (st.st_mode, st.st_mtime_ns, st.st_size, content)
    return result


def _accepted(inputs, eid):
    envelope = json.loads(
        (Path(inputs["sink"]) / "envelopes" / f"{eid}.json").read_text())
    counts = {}
    for record in envelope["records"]:
        counts[record["type"]] = counts.get(record["type"], 0) + 1
    return {"contract": ext.RECEIPT_CONTRACT, "kind": "receive", "status": "accepted",
            "envelope_id": eid, "records_sha256": envelope["records_sha256"],
            "records": envelope["record_count"], "accepted": counts, "acked_at": NOW}


@pytest.mark.parametrize("command", [[], ["deliver"]])
def test_legacy_and_named_delivery_preserve_numeric_hash_envelope_contract(
        inputs, capsys, command):
    code, result = _cli(capsys, [*command, *_flags(inputs)])
    assert code == 0 and result["status"] == "acked"
    envelope = json.loads(
        (Path(inputs["sink"]) / "envelopes" / f'{result["envelope_id"]}.json').read_text())
    expected = ext.build_envelope(
        _records(), ext.load_authorization(inputs["auth"]), NOW - 10)
    assert envelope == expected
    # Fixed /1 bytes hashed independently, not regenerated by this implementation.
    assert envelope["records_sha256"] == \
        "801489b384981cfdf055370dd4de7e6259593b68b4fa69253187885dd603c0f7"
    assert envelope["envelope_id"] == "a208a7570257f3011b4fba1d"
    assert ext._intent_hash(envelope) == \
        "f18599d8abc68d3acb4f11791089144762b4ab88940401527426fc626038a7a8"
    assert ext._canonical({"x": NOW, "small": 0.000001}) == \
        '{"small":1e-06,"x":1800000000.0}'
    assert "part" not in envelope
    assert set(ext.RECORD_TYPES) == {
        "meta", "coverage", "stat", "message", "attachment", "signal", "signals_truncated"}


