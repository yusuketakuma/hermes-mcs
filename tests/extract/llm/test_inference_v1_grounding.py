"""Independent synthetic source/attribute pairs for inference v1 grounding."""
import copy

import pytest

import clinical_scope
import extract_validation as validation


def _med(body, **changes):
    return {"name": "合成薬A", "status": "current", "subject": "patient", "negated": False,
            "evidence": body, **changes}


def _symptom(body, **changes):
    return {"text": "発熱", "status": "ongoing", "subject": "patient", "negated": False,
            "evidence": body, **changes}


def _clean(kind, item, body, *, context=False):
    # Expectations below are source-defined, never generated by the implementation.
    output = validation.validate({kind: [copy.deepcopy(item)]}, body, ctx=context)
    assert output is not None and len(output[kind]) == 1
    return output[kind][0]


def test_person_and_period_are_independent_without_changing_legacy_family_scope():
    body = "母は昨日、発熱なし。本人は現在、発熱あり。"
    start = body.index("発熱")
    assert clinical_scope.source_axes(body, start, start + 2) == ("family", "past")
    assert clinical_scope.patient_source_scope(body, start, start + 2) == "family"
    start = body.rindex("発熱")
    assert clinical_scope.source_axes(body, start, start + 2) == ("patient", "current")


def test_wrong_symptom_person_negation_and_time_degrade_attributes_not_the_report():
    body = "母は昨日、発熱なし。"
    wrong = _clean("symptoms", _symptom(body, status="new"), body)
    assert wrong["text"] == "発熱" and wrong["evidence"] == body
    assert wrong["unverified"] is True
    assert all(key not in wrong for key in ("subject", "status", "negated"))
    correct = _clean("symptoms", _symptom(body, subject="family", status="past", negated=True), body)
    assert correct["subject"] == "family" and correct["status"] == "past" and correct["negated"] is True
    assert not correct.get("unverified")


@pytest.mark.parametrize("text,quote", [("吐き気", "本人は嘔気なし。"), ("むくみ", "本人は浮腫なし。")])
def test_supported_symptom_synonyms_keep_their_negative_fact(text, quote):
    good = _clean("symptoms", _symptom(quote, text=text, negated=True), quote)
    assert good["negated"] is True and not good.get("unverified")
    wrong = _clean("symptoms", _symptom(quote, text=text), quote)
    assert wrong["text"] == text and "negated" not in wrong and wrong["unverified"]


def test_a_different_symptoms_negative_clause_cannot_change_the_target_polarity():
    body = "本人は発熱あり、母は咳なし。"
    good = _clean("symptoms", _symptom(body), body)
    assert good["negated"] is False and good["subject"] == "patient" and not good.get("unverified")
    wrong = _clean("symptoms", _symptom(body, negated=True), body)
    assert "negated" not in wrong and wrong["unverified"]


def test_conditional_symptom_is_not_confirmed_as_an_ongoing_occurrence():
    body = "発熱したら連絡してください。"
    item = _clean("symptoms", _symptom(body), body)
    assert item["text"] == "発熱" and item["evidence"] == body
    assert "status" not in item and item["unverified"]


@pytest.mark.parametrize("context", [False, True])
def test_medication_attributes_cannot_borrow_another_drugs_values(context):
    body = "本人は合成薬Aを5mgで1日2回内服しています。合成薬Bは10mgを頓用で注射しています。"
    claimed = _med(body, dose="10mg", freq="1日3回", route="injection", prn=True)
    wrong = _clean("meds", claimed, body, context=context)
    assert wrong["name"] == "合成薬A" and wrong["evidence"] == body and wrong["unverified"]
    assert wrong["dose"] is None and all(key not in wrong for key in ("freq", "route", "prn"))
    good = _clean("meds", _med(body, dose="5mg", freq="1日2回", route="oral"), body, context=context)
    assert good["dose"] == "5mg" and good["freq"] == "1日2回" and good["route"] == "oral"
    assert not good.get("unverified")


def test_medication_frequency_count_and_prn_allow_source_supported_normalization():
    scheduled = "本人は合成薬Aを朝と夕に各1錠服用しています。"
    good = _clean("meds", _med(scheduled, dose="1回1錠", freq="1日2回", route="oral"), scheduled)
    assert good["dose"] == "1回1錠" and good["freq"] == "1日2回" and not good.get("unverified")
    needed = "本人は合成薬Aを必要なときだけ1錠服用しています。"
    good = _clean("meds", _med(needed, dose="1錠", prn=True, route="oral"), needed)
    assert good["prn"] is True and good["dose"] == "1錠" and not good.get("unverified")


def test_product_strength_and_count_are_not_multiplied_into_an_unreported_dose():
    body = "本人は合成薬Aの5mg錠を2錠内服しています。"
    for dose in ("10mg", "5mg"):
        item = _clean("meds", _med(body, dose=dose), body)
        assert item["name"] == "合成薬A" and item["dose"] is None and item["unverified"]
    good = _clean("meds", _med(body, dose="2錠"), body)
    assert good["dose"] == "2錠" and not good.get("unverified")


@pytest.mark.parametrize("body,status", [("母は以前、合成薬Aを5mg内服していました。", "past"),
    ("母は明日、合成薬Aを5mg内服する予定です。", "planned")])
def test_medication_family_and_period_survive_together(body, status):
    wrong = _clean("meds", _med(body, dose="5mg"), body)
    assert wrong["name"] == "合成薬A" and "subject" not in wrong and "status" not in wrong
    good = _clean("meds", _med(body, dose="5mg", subject="family", status=status), body)
    assert good["subject"] == "family" and good["status"] == status and not good.get("unverified")


def test_medication_explicit_nonuse_is_kept_instead_of_dropping_the_drug():
    body = "本人は合成薬Aを服用していません。"
    wrong = _clean("meds", _med(body), body)
    assert wrong["name"] == "合成薬A" and "negated" not in wrong and wrong["unverified"]
    good = _clean("meds", _med(body, negated=True), body)
    assert good["negated"] is True and not good.get("unverified")


def _request(body, **changes):
    return {"action": "合成資料Xを確認", "to": "薬剤師", "from": None,
            "kind": "request", "evidence": body, **changes}


def test_request_recipient_and_due_do_not_borrow_another_requests_attributes():
    body = "薬剤師へ合成資料Xを確認してください。医師へ2026年10月6日までに合成資料Yを確認してください。"
    wrong = _clean("requests", _request(body, to="医師", due="2026-10-06"), body)
    assert wrong["action"] == "合成資料Xを確認" and wrong["to"] is None
    assert "due" not in wrong and wrong["unverified"]
    good = _clean("requests", _request(body), body)
    assert good["to"] == "薬剤師" and not good.get("unverified")


def test_request_paraphrase_and_explicit_date_keep_supported_attributes():
    body = "合成担当Aから薬剤師へ2026年10月6日までに合成資料Xのご確認をお願いします。"
    item = _clean("requests", _request(body, action="合成資料Xを確認", **{
        "from": "合成担当A", "due": "2026-10-06", "due_text": "2026年10月6日まで"}), body)
    assert item["action"] == "合成資料Xを確認" and item["to"] == "薬剤師"
    assert item["from"] == "合成担当A" and item["due"] == "2026-10-06"
    assert not item.get("unverified")


def test_unsupported_request_action_keeps_its_evidence_without_inventing_the_action():
    body = "薬剤師へ合成資料Xを確認してください。"
    item = _clean("requests", _request(body, action="合成薬Aを中止"), body)
    assert item["evidence"] == body and item["action"] is None and item["unverified"]


def test_relative_due_is_preserved_without_resolving_it_from_the_execution_date():
    body = "薬剤師へ明日までに合成資料Xを確認してください。"
    item = _clean("requests", _request(body, due="2026-10-06", due_text="明日まで"), body)
    assert item["due_text"] == "明日まで" and "due" not in item and item["unverified"]


def test_a_reporter_is_not_automatically_the_request_recipient():
    body = "薬剤師から医師へ合成資料Xを確認してください。"
    wrong = _clean("requests", _request(body), body)
    assert wrong["to"] is None and wrong["unverified"]
    good = _clean("requests", _request(body, to="医師", **{"from": "薬剤師"}), body)
    assert good["to"] == "医師" and good["from"] == "薬剤師" and not good.get("unverified")


@pytest.mark.parametrize("tail,expected", [("しました", False), ("していません", True),
    ("したい", None), ("する予定", None), ("したかもしれません", None)])
def test_shared_polarity_requires_direct_assertion_evidence(tail, expected):
    body = "本人は合成薬Aを中止" + tail
    end = body.index("中止") + 2
    assert clinical_scope.source_polarity(body, 0, len(body), target_end=end) is expected
    assert clinical_scope.source_polarity(body, 0, len(body)) is None


def test_attribute_uncertainty_survives_piece_and_full_source_revalidation():
    body = "本人は合成薬Aを5mgで内服しています。"
    first = _clean("meds", _med(body, dose="10mg"), body)
    second = _clean("meds", first, body)
    assert second["name"] == "合成薬A" and second["dose"] is None and second["unverified"]


def test_daily_total_scope_is_not_silently_removed_from_the_dose():
    body = "本人は合成薬Aを1日3錠内服しています。"
    wrong = _clean("meds", _med(body, dose="3錠"), body)
    assert wrong["dose"] is None and wrong["unverified"]
    good = _clean("meds", _med(body, dose="1日3錠"), body)
    assert good["dose"] == "1日3錠" and not good.get("unverified")


def test_absence_is_not_an_invented_resolved_episode_but_explicit_resolution_survives():
    absent = "本人は発熱なし。"
    wrong = _clean("symptoms", _symptom(absent, status="resolved", negated=True), absent)
    assert wrong["negated"] is True and "status" not in wrong and wrong["unverified"]
    resolved = "本人の発熱は治まりました。"
    good = _clean("symptoms", _symptom(resolved, status="resolved"), resolved)
    assert good["status"] == "resolved" and not good.get("unverified")


def test_request_normalization_does_not_erase_a_particle_inside_the_object_name():
    body = "薬剤師へのぞみ資料を確認してください。"
    wrong = _clean("requests", _request(body, action="ぞみ資料を確認"), body)
    # Even an overlapping spelling must not establish a different named object.
    assert wrong.get("unverified") or wrong["action"] is None


def test_unresolved_drug_reference_retains_the_source_report_but_not_context_dose():
    body = "同薬を中止しました。"
    item = _clean("meds", _med(body, action="stop", dose="5mg"), body, context=True)
    assert item["evidence"] == body and item["action"] == "stop"
    assert item["dose"] is None and item["unverified"]


def test_self_plan_actor_is_kept_without_becoming_the_recipient():
    body = "合成担当Aが合成資料Xを確認する予定です。"
    item = _clean("requests", _request(body, to=None, kind="self_plan", **{"from": "合成担当A"}), body)
    assert item["from"] == "合成担当A" and item["to"] is None
    assert item["kind"] == "self_plan" and not item.get("unverified")
