@pytest.mark.parametrize("context", [False, True])
def test_medication_attributes_cannot_borrow_another_drugs_values(context):
    body = "本人は合成薬Aを5mgで1日2回内服しています。合成薬Bは10mgを頓用で注射しています。"
    claimed = _med(body, dose="10mg", freq="1日3回", route="injection", prn=True)
    wrong = _clean("meds", claimed, body, context=context)
    assert wrong["name"] == "合成薬A" and wrong["evidence"] == body and wrong["unverified"]
    assert wrong["dose"] is None and all(key not in wrong for key in ("freq", "route", "prn"))
    good = _clean("meds", _med(body, dose="5mg", freq="1日2回", route="oral"), body, context=context)
    assert good["dose"] == "5mg" and good["freq"] == "1日2回" and good["route"] == "oral"
    assert not good.get("unverified")


def test_medication_frequency_count_and_prn_allow_source_supported_normalization():
    scheduled = "本人は合成薬Aを朝と夕に各1錠服用しています。"
    good = _clean("meds", _med(scheduled, dose="1回1錠", freq="1日2回", route="oral"), scheduled)
    assert good["dose"] == "1回1錠" and good["freq"] == "1日2回" and not good.get("unverified")
    needed = "本人は合成薬Aを必要なときだけ1錠服用しています。"
    good = _clean("meds", _med(needed, dose="1錠", prn=True, route="oral"), needed)
    assert good["prn"] is True and good["dose"] == "1錠" and not good.get("unverified")


