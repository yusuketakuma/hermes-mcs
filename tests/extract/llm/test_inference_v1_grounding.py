"""Independent synthetic source/attribute pairs for inference v1 grounding."""
import copy

import pytest

import clinical_scope
import extract_validation as validation
import extract_quality


def _med(body, **changes):
    return {"name": "合成薬A", "status": "current", "subject": "patient", "negated": False,
            "evidence": body, **changes}


def _symptom(body, **changes):
    return {"text": "発熱", "status": "ongoing", "subject": "patient", "negated": False,
            "evidence": body, **changes}


def _clean(kind, item, body, *, context=False):
    # Expectations below are source-defined, never generated by the implementation.
    output = validation.validate({kind: [copy.deepcopy(item)]}, body, ctx=context)
    assert output is not None and len(output[kind]) == 1
    return output[kind][0]


def test_person_and_period_are_independent_without_changing_legacy_family_scope():
    body = "母は昨日、発熱なし。本人は現在、発熱あり。"
    start = body.index("発熱")
    assert clinical_scope.source_axes(body, start, start + 2) == ("family", "past")
    assert clinical_scope.patient_source_scope(body, start, start + 2) == "family"
    start = body.rindex("発熱")
    assert clinical_scope.source_axes(body, start, start + 2) == ("patient", "current")


def test_wrong_symptom_person_negation_and_time_degrade_attributes_not_the_report():
    body = "母は昨日、発熱なし。"
    wrong = _clean("symptoms", _symptom(body, status="new"), body)
    assert wrong["text"] == "発熱" and wrong["evidence"] == body
    assert wrong["unverified"] is True
    assert all(key not in wrong for key in ("subject", "status", "negated"))
    correct = _clean("symptoms", _symptom(body, subject="family", status="past", negated=True), body)
    assert correct["subject"] == "family" and correct["status"] == "past" and correct["negated"] is True
    assert not correct.get("unverified")


@pytest.mark.parametrize("text,quote", [("吐き気", "本人は嘔気なし。"), ("むくみ", "本人は浮腫なし。")])
def test_supported_symptom_synonyms_keep_their_negative_fact(text, quote):
    good = _clean("symptoms", _symptom(quote, text=text, negated=True), quote)
    assert good["negated"] is True and not good.get("unverified")
    wrong = _clean("symptoms", _symptom(quote, text=text), quote)
    assert wrong["text"] == text and "negated" not in wrong and wrong["unverified"]


